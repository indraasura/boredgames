// The source lines run in an arbitrary direction; these are driven the other way in real life.
const REVERSE = new Set(["sg-2008", "ru-2014", "fr-1969"]);

const out = [];
for (const f of geo.features) {
  const p = f.properties;
  const [country, flag, short] = META[p.id] ?? [p.Location, "🏁", p.Location];
  let c = f.geometry.coordinates.slice();
  // Closed ring: drop the repeated end point.
  const a = c[0], b = c[c.length - 1];
  if (a[0] === b[0] && a[1] === b[1]) c.pop();
  if (REVERSE.has(p.id)) c = [c[0], ...c.slice(1).reverse()];
  const lat0 = c.reduce((s, q) => s + q[1], 0) / c.length;
  const lon0 = c.reduce((s, q) => s + q[0], 0) / c.length;
  const k = Math.cos((lat0 * Math.PI) / 180);
  const pts = c.map((q) => [Math.round((q[0] - lon0) * 111320 * k * 10) / 10, Math.round((q[1] - lat0) * 110540 * 10) / 10]);
  out.push({ id: p.id, name: p.Name, short, location: p.Location, country, flag, length: p.length, altitude: p.altitude, firstGp: p.firstgp, pts: pts.flat() });
}

const body = out.map((o) => `  ${JSON.stringify(o)},`).join("\n");
fs.writeFileSync(
  new URL("../src/circuits.data.ts", import.meta.url),
  `// Generated by scripts/gen-circuits.mjs from github.com/bacinger/f1-circuits (MIT). Do not edit.\n` +
    `export interface CircuitData {\n  id: string;\n  name: string;\n  short: string;\n  location: string;\n  country: string;\n  flag: string;\n  /** Official lap length, metres. */\n  length: number;\n  /** Metres above sea level. */\n  altitude: number;\n  firstGp: number;\n  /** Centre line as x,y pairs in metres, starting on the start/finish line. */\n  pts: number[];\n}\n\n` +
    `export const CIRCUIT_DATA: CircuitData[] = [\n${body}\n];\n`,
);
