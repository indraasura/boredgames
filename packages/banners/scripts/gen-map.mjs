// Builds src/map.data.ts: the continent, its provinces (Voronoi cells clipped to the coast) and which provinces border each other.
// Run with: pnpm --filter @boredgames/banners gen-map
import fs from "node:fs";
import { Delaunay } from "d3-delaunay";
import polygonClipping from "polygon-clipping";

const W = 1600;
const H = 1000;

// name, x, y, terrain, income, crown
const P = [
  // North-west: House Varn
  ["Varnhold", 300, 270, "plains", 3, true],
  ["Ashford", 445, 175, "plains", 2, false],
  ["Greywater", 205, 425, "plains", 2, false],
  ["Thornfield", 420, 360, "forest", 1, false],
  ["Wyrmwood", 575, 270, "forest", 1, false],
  // North-east: House Aldmoor
  ["Aldmoor", 1300, 250, "plains", 3, true],
  ["Frostgate", 1155, 165, "hills", 1, false],
  ["Eastmarch", 1185, 345, "plains", 2, false],
  ["Ravensholt", 1420, 410, "forest", 1, false],
  ["Pinecrest", 1020, 285, "forest", 2, false],
  // South-east: House Brennic
  ["Goldhaven", 1295, 770, "plains", 3, true],
  ["Duskvale", 1150, 650, "plains", 2, false],
  ["Redcliff", 1430, 610, "hills", 1, false],
  ["Marrowby", 1080, 815, "forest", 1, false],
  // South-west: House Corvain
  ["Stormcliff", 300, 745, "plains", 3, true],
  ["Fenmoor", 190, 600, "forest", 1, false],
  ["Oakheart", 445, 655, "forest", 2, false],
  ["Southwatch", 470, 860, "plains", 1, false],
  // The heartland
  ["Highcrag", 800, 220, "hills", 3, true],
  ["Kingsreach", 800, 495, "plains", 3, true],
  ["Saltmere", 800, 800, "plains", 3, true],
  ["Midmarch", 615, 450, "plains", 2, false],
  ["Riverholm", 975, 470, "plains", 2, false],
  ["Westvale", 615, 640, "plains", 2, false],
  ["Ironhill", 985, 640, "hills", 2, false],
  ["Emberfield", 960, 360, "plains", 1, false],
];

// The coast: a rough outline, then made ragged with a deterministic midpoint wobble.
const rough = [
  [110, 300], [170, 170], [300, 115], [460, 90], [620, 130], [760, 95], [900, 120], [1060, 95], [1230, 100], [1380, 140],
  [1500, 230], [1535, 380], [1500, 500], [1545, 620], [1480, 770], [1390, 880], [1240, 915], [1080, 900], [930, 920],
  [800, 885], [660, 920], [520, 935], [380, 900], [240, 850], [140, 760], [95, 630], [130, 520], [80, 420],
];
let seed = 11;
const rnd = () => ((seed = (seed * 1664525 + 1013904223) >>> 0) / 4294967296) * 2 - 1;
let coast = rough;
for (let pass = 0; pass < 4; pass++) {
  const next = [];
  const amp = [34, 18, 9, 4][pass];
  for (let i = 0; i < coast.length; i++) {
    const a = coast[i];
    const b = coast[(i + 1) % coast.length];
    next.push(a);
    const mx = (a[0] + b[0]) / 2;
    const my = (a[1] + b[1]) / 2;
    const dx = b[0] - a[0];
    const dy = b[1] - a[1];
    const len = Math.hypot(dx, dy) || 1;
    const k = rnd() * amp;
    next.push([mx + (-dy / len) * k, my + (dx / len) * k]);
  }
  coast = next;
}
coast = coast.map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]);

const pts = P.map((p) => [p[1], p[2]]);
const del = Delaunay.from(pts);
const vor = del.voronoi([0, 0, W, H]);

const inside = (x, y) => {
  let c = false;
  for (let i = 0, j = coast.length - 1; i < coast.length; j = i++) {
    const [xi, yi] = coast[i];
    const [xj, yj] = coast[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) c = !c;
  }
  return c;
};

const cells = P.map((_, i) => {
  const cell = vor.cellPolygon(i);
  const clipped = polygonClipping.intersection([cell], [[...coast, coast[0]]]);
  // Keep the largest piece.
  let best = null;
  let bestA = 0;
  for (const poly of clipped) {
    const ring = poly[0];
    let a = 0;
    for (let k = 0; k < ring.length - 1; k++) a += ring[k][0] * ring[k + 1][1] - ring[k + 1][0] * ring[k][1];
    if (Math.abs(a) > bestA) {
      bestA = Math.abs(a);
      best = ring;
    }
  }
  return best.slice(0, -1).map(([x, y]) => [Math.round(x * 10) / 10, Math.round(y * 10) / 10]);
});

// Neighbours: Delaunay neighbours whose shared Voronoi edge is on land and not tiny.
const adj = P.map(() => new Set());
for (let i = 0; i < P.length; i++) {
  for (const j of del.neighbors(i)) {
    if (j <= i) continue;
    const ci = vor.cellPolygon(i);
    const cj = vor.cellPolygon(j);
    // shared edge: vertices common to both cells
    const common = ci.filter(([x, y]) => cj.some(([u, v]) => Math.abs(u - x) < 0.01 && Math.abs(v - y) < 0.01));
    if (common.length < 2) continue;
    const [a, b] = common;
    // sample the edge: how much of it is on land
    let land = 0;
    const N = 20;
    for (let k = 0; k <= N; k++) if (inside(a[0] + ((b[0] - a[0]) * k) / N, a[1] + ((b[1] - a[1]) * k) / N)) land++;
    const len = Math.hypot(b[0] - a[0], b[1] - a[1]);
    if ((land / (N + 1)) * len > 30) {
      adj[i].add(j);
      adj[j].add(i);
    }
  }
}

const provinces = P.map((p, i) => ({
  id: i,
  name: p[0],
  x: p[1],
  y: p[2],
  terrain: p[3],
  income: p[4],
  crown: p[5],
  adj: [...adj[i]].sort((a, b) => a - b),
  poly: cells[i].flat(),
}));

const body = `// Generated by scripts/gen-map.mjs. Do not edit by hand.
export const MAP_W = ${W};
export const MAP_H = ${H};
export const COAST: number[] = ${JSON.stringify(coast.flat())};
export const PROVINCE_DATA = ${JSON.stringify(provinces)} as const;
`;
fs.writeFileSync(new URL("../src/map.data.ts", import.meta.url), body);
for (const p of provinces) console.log(p.id, p.name.padEnd(11), p.adj.map((j) => provinces[j].name).join(", "));
